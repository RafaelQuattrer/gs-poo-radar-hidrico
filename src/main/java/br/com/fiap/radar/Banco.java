package br.com.fiap.radar;

import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.SQLException;

public final class Banco {
    private final String url;

    public Banco(String url) {
        this.url = url;
    }

    Connection abrir() throws SQLException {
        return DriverManager.getConnection(url, "sa", "");
    }

    public void inicializar() {
        try (var conexao = abrir(); var sql = conexao.createStatement()) {
            sql.executeUpdate("""
                    CREATE TABLE IF NOT EXISTS medicoes (
                        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        sensor_id VARCHAR(20) NOT NULL,
                        tipo VARCHAR(20) NOT NULL,
                        valor DOUBLE PRECISION NOT NULL,
                        coletada_em TIMESTAMP WITH TIME ZONE NOT NULL
                    )
                    """);
            sql.executeUpdate("""
                    CREATE INDEX IF NOT EXISTS idx_medicoes_sensor
                    ON medicoes (sensor_id, id)
                    """);
            sql.executeUpdate("""
                    CREATE TABLE IF NOT EXISTS alertas (
                        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        sensor_id VARCHAR(20) NOT NULL,
                        tipo VARCHAR(20) NOT NULL,
                        nivel VARCHAR(20) NOT NULL,
                        previsto DOUBLE PRECISION NOT NULL,
                        limiar DOUBLE PRECISION NOT NULL,
                        estrategia VARCHAR(60) NOT NULL,
                        emitido_em TIMESTAMP WITH TIME ZONE NOT NULL
                    )
                    """);
        } catch (SQLException causa) {
            throw new FonteIndisponivelException("Não foi possível inicializar o banco H2.", causa);
        }
    }
}
